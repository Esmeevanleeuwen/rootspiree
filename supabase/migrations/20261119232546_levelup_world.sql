REVOKE ALL ON ALL TABLES IN SCHEMA levelup FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA levelup FROM PUBLIC;

DO $$
DECLARE
  role_name TEXT;
  table_name TEXT;
BEGIN
  FOREACH role_name IN ARRAY ARRAY['anon', 'authenticated', 'service_role'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = role_name) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA levelup FROM %I', role_name);
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA levelup FROM %I', role_name);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA levelup FROM %I', role_name);
    END IF;
  END LOOP;

  FOREACH table_name IN ARRAY ARRAY[
    'accounts', 'sessions', 'world_profiles', 'world_npcs',
    'world_quests', 'world_quest_drafts', 'world_posts', 'world_votes'
  ] LOOP
    EXECUTE format('ALTER TABLE levelup.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format(
      'CREATE POLICY game_server ON levelup.%I TO levelup_app USING (true) WITH CHECK (true)',
      table_name
    );
  END LOOP;
END
$$;

GRANT USAGE ON SCHEMA levelup TO levelup_app;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA levelup TO levelup_app;
GRANT SELECT, INSERT, UPDATE ON levelup.accounts, levelup.world_profiles, levelup.world_quests TO levelup_app;
GRANT SELECT, INSERT, DELETE ON levelup.sessions, levelup.world_votes TO levelup_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON levelup.world_quest_drafts TO levelup_app;
GRANT SELECT, INSERT ON levelup.world_npcs, levelup.world_posts TO levelup_app;
