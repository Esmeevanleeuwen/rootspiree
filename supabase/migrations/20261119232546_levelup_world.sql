CREATE SCHEMA levelup;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'levelup_app') THEN
    CREATE ROLE levelup_app NOLOGIN NOINHERIT;
  END IF;
END
$$;

REVOKE ALL ON SCHEMA levelup FROM PUBLIC;

CREATE TABLE levelup.accounts (
  id TEXT PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('player', 'admin')),
  password_hash TEXT NOT NULL,
  profile_json TEXT NOT NULL,
  profile_complete INTEGER NOT NULL DEFAULT 0,
  onboarding_complete INTEGER NOT NULL DEFAULT 0,
  language TEXT NOT NULL CHECK (language IN ('en', 'nl')),
  type_scores TEXT,
  created_at BIGINT NOT NULL
);

CREATE TABLE levelup.sessions (
  token_hash TEXT PRIMARY KEY,
  account_id TEXT NOT NULL REFERENCES levelup.accounts(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);

CREATE INDEX sessions_account_idx ON levelup.sessions(account_id);
CREATE INDEX sessions_expiry_idx ON levelup.sessions(expires_at);

CREATE TABLE levelup.world_profiles (
  account_id TEXT PRIMARY KEY REFERENCES levelup.accounts(id) ON DELETE CASCADE,
  bio TEXT NOT NULL DEFAULT '',
  journey TEXT,
  type_scores TEXT
);

CREATE TABLE levelup.world_npcs (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  role TEXT NOT NULL,
  avatar TEXT NOT NULL,
  description TEXT NOT NULL,
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE levelup.world_quests (
  id TEXT PRIMARY KEY,
  player_id TEXT NOT NULL,
  goal_id TEXT,
  name TEXT NOT NULL,
  description TEXT NOT NULL,
  state TEXT NOT NULL CHECK (state IN ('Open', 'Ingeleverd', 'Behaald', 'Niet behaald')),
  plus INTEGER NOT NULL CHECK (plus BETWEEN 0 AND 999),
  minus INTEGER NOT NULL CHECK (minus BETWEEN 0 AND 999),
  evidence TEXT,
  feedback TEXT,
  private_steps TEXT,
  submission_prompt TEXT,
  completion_criteria TEXT,
  shared_goal_id TEXT,
  assigned_by TEXT REFERENCES levelup.accounts(id) ON DELETE SET NULL,
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE UNIQUE INDEX world_open_exercise ON levelup.world_quests(player_id, goal_id)
  WHERE state = 'Open' AND goal_id IS NOT NULL;

CREATE TABLE levelup.world_quest_drafts (
  id TEXT PRIMARY KEY,
  admin_id TEXT NOT NULL REFERENCES levelup.accounts(id) ON DELETE CASCADE,
  content TEXT NOT NULL,
  updated_at BIGINT NOT NULL,
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE INDEX world_quest_drafts_admin_idx
  ON levelup.world_quest_drafts(admin_id, updated_at DESC, rowid DESC);

CREATE TABLE levelup.world_posts (
  id TEXT PRIMARY KEY,
  player_id TEXT NOT NULL,
  message TEXT NOT NULL,
  rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE levelup.world_votes (
  post_id TEXT NOT NULL REFERENCES levelup.world_posts(id) ON DELETE CASCADE,
  account_id TEXT NOT NULL REFERENCES levelup.accounts(id) ON DELETE CASCADE,
  PRIMARY KEY (post_id, account_id)
);

CREATE INDEX world_votes_account_idx ON levelup.world_votes(account_id);

